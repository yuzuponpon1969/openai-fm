def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def validate_inputs() -> dict[str, list[str]]:
    expected = {f"1-{i:03d}" for i in range(1, 73)}
    actual = set(MATERIALS)
    if actual != expected:
        raise AssertionError(f"Material set mismatch: missing={sorted(expected-actual)}, extra={sorted(actual-expected)}")
    mapped = {m for values in ITEM_MATERIALS.values() for m in values}
    if mapped != expected:
        raise AssertionError(f"O-column mapping mismatch: missing={sorted(expected-mapped)}, extra={sorted(mapped-expected)}")
    if len(ITEM_MATERIALS) != 59:
        raise AssertionError(f"Expected 59 items, got {len(ITEM_MATERIALS)}")
    if not any(len(v) >= 5 for v in ITEM_MATERIALS.values()):
        raise AssertionError("No multi-material item found")
    inverse = inverse_mapping()
    if not any(len(v) >= 5 for v in inverse.values()):
        raise AssertionError("No material reused across multiple items")
    return inverse


