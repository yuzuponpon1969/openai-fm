def folder_for_material(number: str) -> str:
    idx = int(number.split("-")[1])
    for start, end, folder in FOLDER_RANGES:
        if start <= idx <= end:
            return folder
    raise ValueError(f"No folder for {number}")


def inverse_mapping() -> dict[str, list[str]]:
    result: dict[str, list[str]] = defaultdict(list)
    for item, material_numbers in ITEM_MATERIALS.items():
        for material_number in material_numbers:
            result[material_number].append(item)
    return {key: sorted(value, key=lambda x: [int(p) for p in x.split("-")]) for key, value in result.items()}


def find_japanese_font() -> Path:
    candidates = [
        Path("/usr/share/fonts/opentype/ipaexfont-gothic/ipaexg.ttf"),
        Path("/usr/share/fonts/opentype/ipaexfont/ipaexg.ttf"),
        Path("/usr/share/fonts/truetype/ipaexg.ttf"),
        Path("/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf"),
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    for root in [Path("/usr/share/fonts"), Path("/usr/local/share/fonts")]:
        if root.exists():
            for name in ("ipaexg.ttf", "ipag.ttf", "NotoSansCJK-Regular.ttc"):
                matches = list(root.rglob(name))
                if matches:
                    return matches[0]
    raise FileNotFoundError("Japanese font not found")


def register_fonts() -> str:
    font_path = find_japanese_font()
    font_name = "JABJTE-JP"
    try:
        pdfmetrics.registerFont(TTFont(font_name, str(font_path)))
    except Exception:
        # Some TTC builds require a subfont index.
        pdfmetrics.registerFont(TTFont(font_name, str(font_path), subfontIndex=0))
    return font_name


