def create_zip(source_root: Path, output_path: Path, arc_root: Path | None = None) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for file_path in sorted(source_root.rglob("*")):
            if not file_path.is_file():
                continue
            if arc_root is None:
                arcname = file_path.relative_to(source_root.parent)
            else:
                arcname = arc_root / file_path.relative_to(source_root)
            zf.write(file_path, arcname.as_posix())


def main() -> None:
    inverse = validate_inputs()
    if OUTPUT_ROOT.exists():
        shutil.rmtree(OUTPUT_ROOT)
    SCHOOL_ROOT.mkdir(parents=True, exist_ok=True)
    OPERATOR_ROOT.mkdir(parents=True, exist_ok=True)

    font_name = register_fonts()
    styles = make_styles(font_name)
    pdf_results: list[dict[str, Any]] = []

    for number in sorted(MATERIALS):
        data = MATERIALS[number]
        folder = SCHOOL_ROOT / folder_for_material(number)
        filename = f"{number}_{data['title']}.pdf"
        path = folder / filename
        build_material_pdf(path, number, data, inverse[number], styles)

        reader = PdfReader(str(path))
        extracted = "\n".join((page.extract_text() or "") for page in reader.pages)
        if number not in extracted:
            raise AssertionError(f"Material number missing from extracted text: {number}")
        if data["title"] not in extracted:
            raise AssertionError(f"Title missing from extracted text: {number}")
        if len(extracted) < 700:
            raise AssertionError(f"Insufficient extracted text for {number}: {len(extracted)}")
        if len(reader.pages) < 2:
            raise AssertionError(f"PDF should have at least 2 pages: {number}")
        relative = path.relative_to(PACKAGE_ROOT).as_posix()
        pdf_results.append({
            "number": number,
            "title": data["title"],
            "relative_path": relative,
            "pages": len(reader.pages),
            "text_length": len(extracted),
            "sha256": sha256_file(path),
        })
        print(f"Generated {number}: {len(reader.pages)} pages, {len(extracted)} chars")

    create_readme(inverse, pdf_results)

    if len(pdf_results) != 72:
        raise AssertionError(f"Expected 72 PDFs, got {len(pdf_results)}")
    filenames = [r["relative_path"] for r in pdf_results]
    if len(filenames) != len(set(filenames)):
        raise AssertionError("Duplicate PDF paths")

    full_zip = OUTPUT_ROOT / f"{PACKAGE_NAME}.zip"
    school_zip = OUTPUT_ROOT / f"{SCHOOL_FOLDER_NAME}_学校フォルダのみ.zip"
    create_zip(PACKAGE_ROOT, full_zip)
    create_zip(SCHOOL_ROOT, school_zip, Path(SCHOOL_FOLDER_NAME))

    package_manifest = {
        "full_package_zip": {"name": full_zip.name, "sha256": sha256_file(full_zip), "size": full_zip.stat().st_size},
        "school_folder_zip": {"name": school_zip.name, "sha256": sha256_file(school_zip), "size": school_zip.stat().st_size},
        "pdf_count": 72,
        "total_pages": sum(r["pages"] for r in pdf_results),
    }
    (OUTPUT_ROOT / "artifact-manifest.json").write_text(json.dumps(package_manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(package_manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
