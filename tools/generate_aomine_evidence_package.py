def draw_simple_table(c: canvas.Canvas, rows: list[tuple[str, str, str]], y: float) -> float:
    x0 = 42
    widths = [80, 100, 320]
    row_h = 34
    headers = ("年度", "区分", "記録概要")
    all_rows = [headers, *rows]
    c.setLineWidth(0.5)
    for r_index, row in enumerate(all_rows):
        x = x0
        if r_index == 0:
            c.setFillGray(0.92)
            c.rect(x0, y - row_h, sum(widths), row_h, fill=1, stroke=1)
            c.setFillGray(0)
        else:
            c.rect(x0, y - row_h, sum(widths), row_h, fill=0, stroke=1)
        for col, width in zip(row, widths):
            c.rect(x, y - row_h, width, row_h, fill=0, stroke=1)
            c.setFont("JP", 8.5)
            wrapped = wrap_ja(col, max(8, int(width / 9)))[:2]
            yy = y - 13
            for line in wrapped:
                c.drawString(x + 4, yy, line)
                yy -= 11
            x += width
        y -= row_h
    return y - 12


