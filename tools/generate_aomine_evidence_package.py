def safe_filename(text: str) -> str:
    return re.sub(r"[\\/:*?\"<>|]", "・", text)


def wrap_ja(text: str, width: int = 48) -> list[str]:
    lines: list[str] = []
    for paragraph in str(text).splitlines() or [""]:
        paragraph = paragraph.strip()
        if not paragraph:
            lines.append("")
            continue
        while len(paragraph) > width:
            cut = width
            for punctuation in ("。", "、", "）", "」", "：", "；"):
                pos = paragraph.rfind(punctuation, 0, width + 1)
                if pos >= max(12, width - 10):
                    cut = pos + 1
                    break
            lines.append(paragraph[:cut])
            paragraph = paragraph[cut:]
        lines.append(paragraph)
    return lines


def draw_lines(c: canvas.Canvas, lines: Iterable[str], x: float, y: float, *, size: float = 10.5, leading: float = 17, bullet: bool = False) -> float:
    c.setFont("JP", size)
    for raw in lines:
        prefix = "・" if bullet else ""
        wrapped = wrap_ja(prefix + raw, 48 if bullet else 52)
        for line in wrapped:
            if y < 55:
                return y
            c.drawString(x, y, line)
            y -= leading
        y -= 3
    return y


