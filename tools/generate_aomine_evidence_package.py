def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    if OUTPUT_ROOT.exists():
        shutil.rmtree(OUTPUT_ROOT)
    SCHOOL_ROOT.mkdir(parents=True)
    for _, _, folder in SUBFOLDERS:
        (SCHOOL_ROOT / folder).mkdir(parents=True, exist_ok=True)

    font_path = find_font()
    try:
        pdfmetrics.registerFont(TTFont("JP", font_path, subfontIndex=0))
    except TypeError:
        pdfmetrics.registerFont(TTFont("JP", font_path))

    records: list[dict[str, object]] = []
    for doc_id, title in TITLES.items():
        pages = PAGE_COUNTS[doc_id]
        folder = SCHOOL_ROOT / folder_for(doc_id)
        filename = safe_filename(f"{doc_id}_{title}.pdf")
        output_file = folder / filename
        create_pdf(doc_id, title, pages, output_file)

        reader = PdfReader(str(output_file))
        extracted = "\n".join((page.extract_text() or "") for page in reader.pages)
        if len(reader.pages) != pages:
            raise RuntimeError(f"page count mismatch: {doc_id}")
        if doc_id not in extracted:
            raise RuntimeError(f"source number not extractable: {doc_id}")
        if title[:6] not in extracted:
            raise RuntimeError(f"title not extractable: {doc_id}")
        records.append({
            "資料番号": doc_id,
            "資料名": title,
            "PDFファイル": str(output_file.relative_to(SCHOOL_ROOT)).replace("\\", "/"),
            "ページ数": pages,
            "SHA-256": sha256(output_file),
        })

    with (SCHOOL_ROOT / "資料一覧.csv").open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["資料番号", "資料名", "PDFファイル", "ページ数", "SHA-256"])
        writer.writeheader()
        writer.writerows(records)

